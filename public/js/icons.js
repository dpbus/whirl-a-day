/** Inline SVG markup for an icon. Decorative by default; the button around it carries the label. */
export function icon(name, { size = 20 } = {}) {
  const body = ICONS[name];
  if (!body) throw new Error(`Unknown icon: ${name}`);
  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

/** Fill every <span data-icon="name"></span> placeholder in static HTML. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll("[data-icon]")) el.outerHTML = icon(el.dataset.icon, { size: Number(el.dataset.size) || 20 });
}
